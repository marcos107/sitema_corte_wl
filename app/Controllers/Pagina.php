            $abas['lista_tarefas_adm'] = [
                'label' => 'Lista de Tarefas ADM',
                'url' => site_url('public/lista_Tarefas_adm?embed=1')
            ];
        }

        if ($this->usuarioTemPermissao($permissoesUsuario, ['Desenhos cortados', 'Desenhos_Cortados', 'desenhos_cortados', 'Tarefas Concluidas'])) {
            $abas['desenhos_cortados'] = [
                'label' => 'Tarefas Concluidas',
                'url' => site_url('public/desenhos_cortados?embed=1')
            ];
        }

        if (empty($abas)) {
            Login::logout();
            return;
        }

        if (!array_key_exists($abaInicial, $abas)) {
            $abaInicial = array_key_first($abas);
        }

        $array_view = [
            'titulo' => 'Painel de Tarefas',
            'functionType' => 'Painel de Tarefas',
            'nomeUsuario' => Ferramentas::decodificador(Ferramentas::array_index($_SESSION, ['usuario_nome'])),
            'menu' => $this->menu('desenhos', 'painel_tarefas'),
            'abas' => $abas,
            'aba_inicial' => $abaInicial
        ];

        echo view('lista_unificada', $array_view);
    }

