    private function usuarioTemPermissao(array $permissoesUsuario, array $permissoesPermitidas): bool
    {
        if (in_array('all', $permissoesUsuario)) {
            return true;
        }

        foreach ($permissoesPermitidas as $permissao) {
            if (in_array($permissao, $permissoesUsuario) || in_array(str_replace(' ', '_', $permissao), $permissoesUsuario)) {
                return true;
            }
        }

        return false;
    }

    private function renderPainelListasUnificadas(string $abaInicial = 'desenho_meus')
    {
        if (session_status() !== PHP_SESSION_ACTIVE) {
            session_start();
        }

        $permissoesUsuario = Ferramentas::array_index($_SESSION, ['permissao']);
        if (!is_array($permissoesUsuario)) {
            $permissoesUsuario = [];
        }

        $abas = [];

        if ($this->usuarioTemPermissao($permissoesUsuario, ['Meus Desenhos', 'Meus_Desenhos'])) {
            $abas['desenho_meus'] = [
                'label' => 'Meus Desenhos',
                'url' => site_url('public/desenho_meus?embed=1')
            ];
        }

        if ($this->usuarioTemPermissao($permissoesUsuario, ['Lista De Corte', 'Lista_De_Corte', 'Lista De Corte Cortador', 'Lista_De_Corte_Cortador'])) {
            $abas['lista_tarefas'] = [
                'label' => 'Lista de Tarefas',
                'url' => site_url('public/lista_Tarefas?embed=1')
